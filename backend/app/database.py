"""
Database connections for ITBIS.

PostgreSQL holds fixed-structure relational data:
- users
- employees
- incidents
- alerts

MongoDB holds flexible-structure data:
- activity_logs
- behavioral_baselines
- rule_anomalies

Both connections are configured through environment variables
(see .env.example).
"""

import os

from dotenv import load_dotenv
from sqlalchemy import create_engine
from sqlalchemy.orm import sessionmaker, declarative_base
from pymongo import MongoClient


# ---------------------------------------------------------
# Load environment variables
# ---------------------------------------------------------

load_dotenv()


# ---------------------------------------------------------
# PostgreSQL configuration
# ---------------------------------------------------------

DATABASE_URL = os.getenv(
    "DATABASE_URL",
    "postgresql://postgres:yourpassword@localhost:5432/itbis"
)


# ---------------------------------------------------------
# MongoDB configuration
# ---------------------------------------------------------

MONGO_URL = os.getenv(
    "MONGO_URL",
    "mongodb://localhost:27017"
)

MONGO_DB_NAME = os.getenv(
    "MONGO_DB_NAME",
    "itbis"
)


# ---------------------------------------------------------
# PostgreSQL setup
# ---------------------------------------------------------

# connect_args is required for SQLite.
# It is not needed for PostgreSQL.

connect_args = (
    {"check_same_thread": False}
    if DATABASE_URL.startswith("sqlite")
    else {}
)

engine = create_engine(
    DATABASE_URL,
    connect_args=connect_args
)


SessionLocal = sessionmaker(
    autocommit=False,
    autoflush=False,
    bind=engine
)


Base = declarative_base()


# ---------------------------------------------------------
# FastAPI database dependency
# ---------------------------------------------------------

def get_db():
    """
    FastAPI dependency that provides a database session
    and closes it after the request is completed.
    """

    db = SessionLocal()

    try:
        yield db
    finally:
        db.close()


# ---------------------------------------------------------
# MongoDB setup
# ---------------------------------------------------------

mongo_client = MongoClient(MONGO_URL)

mongo_db = mongo_client[MONGO_DB_NAME]


# ---------------------------------------------------------
# MongoDB collections
# ---------------------------------------------------------

# Activity logs generated by employees.
activity_logs_collection = mongo_db["activity_logs"]


# Behavioral baselines calculated for each employee.
behavioral_baselines_collection = mongo_db["behavioral_baselines"]


# Rule-based anomalies detected from employee activity.
# Added for Milestone 2 - Day 15–16.
rule_anomalies_collection = mongo_db["rule_anomalies"]


ml_anomalies_collection = mongo_db["ml_anomalies"]


# ---------------------------------------------------------
# MongoDB indexes
# ---------------------------------------------------------

# Milestone 2 - Day 10
#
# Makes employee activity-log queries faster,
# especially when calculating behavioral baselines.


ml_anomalies_collection.create_index(
    [
        ("employee_id", 1),
        ("date", -1)
    ]
)

activity_logs_collection.create_index(
    [
        ("employee_id", 1),
        ("timestamp", -1)
    ]
)


# Makes event-type based activity queries faster.

activity_logs_collection.create_index(
    [
        ("event_type", 1),
        ("timestamp", -1)
    ]
)


# Milestone 2 - Day 15–16
#
# Makes employee-specific anomaly queries faster.

rule_anomalies_collection.create_index(
    [
        ("employee_id", 1),
        ("detected_at", -1)
    ]
)