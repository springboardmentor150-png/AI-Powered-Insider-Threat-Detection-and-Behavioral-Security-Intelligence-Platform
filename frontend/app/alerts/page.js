"use client";

import { useEffect, useMemo, useState } from "react";
import Link from "next/link";
import { useRouter } from "next/navigation";
import AuthGuard from "@/components/AuthGuard";
import api, { clearSession, isLoggedIn } from "@/lib/api";

export default function AlertsPage() {
  const router = useRouter();

  const [alerts, setAlerts] = useState([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState("");

  const [search, setSearch] = useState("");
  const [severityFilter, setSeverityFilter] = useState("all");

  useEffect(() => {
    if (!isLoggedIn()) {
      router.replace("/login");
      return;
    }

    loadAlerts();
  }, [router]);

  const loadAlerts = async () => {
    try {
      setLoading(true);
      setError("");

      /*
       * Existing backend endpoint:
       * GET /alerts
       */
      const response = await api.get("/alerts");

      const data = Array.isArray(response.data)
        ? response.data
        : response.data?.alerts || [];

      setAlerts(data);
    } catch (err) {
      console.error("Alerts loading error:", err);

      if (err?.response?.status === 401) {
        clearSession();
        router.replace("/login");
        return;
      }

      setError(
        err?.response?.data?.detail ||
          "Unable to load security alerts."
      );
    } finally {
      setLoading(false);
    }
  };

  const filteredAlerts = useMemo(() => {
    let data = [...alerts];

    if (severityFilter !== "all") {
      data = data.filter(
        (alert) =>
          String(alert.severity || "").toLowerCase() ===
          severityFilter.toLowerCase()
      );
    }

    if (search.trim()) {
      const query = search.toLowerCase();

      data = data.filter((alert) =>
        JSON.stringify(alert).toLowerCase().includes(query)
      );
    }

    return data;
  }, [alerts, severityFilter, search]);

  const stats = useMemo(() => {
    return {
      total: alerts.length,

      critical: alerts.filter(
        (a) =>
          String(a.severity || "").toLowerCase() ===
          "critical"
      ).length,

      high: alerts.filter(
        (a) =>
          String(a.severity || "").toLowerCase() ===
          "high"
      ).length,

      medium: alerts.filter(
        (a) =>
          String(a.severity || "").toLowerCase() ===
          "medium"
      ).length,

      low: alerts.filter(
        (a) =>
          String(a.severity || "").toLowerCase() ===
          "low"
      ).length,
    };
  }, [alerts]);

  const getSeverityClass = (severity) => {
    const value = String(severity || "").toLowerCase();

    if (value === "critical") {
      return "border-red-500/30 bg-red-500/10 text-red-400";
    }

    if (value === "high") {
      return "border-orange-500/30 bg-orange-500/10 text-orange-400";
    }

    if (value === "medium") {
      return "border-yellow-500/30 bg-yellow-500/10 text-yellow-400";
    }

    if (value === "low") {
      return "border-green-500/30 bg-green-500/10 text-green-400";
    }

    return "border-slate-600 bg-slate-800 text-slate-400";
  };

  const getStatusClass = (status) => {
    const value = String(status || "").toLowerCase();

    if (value === "resolved") {
      return "border-green-500/30 bg-green-500/10 text-green-400";
    }

    if (value === "investigating") {
      return "border-blue-500/30 bg-blue-500/10 text-blue-400";
    }

    return "border-yellow-500/30 bg-yellow-500/10 text-yellow-400";
  };

  const formatDate = (value) => {
    if (!value) return "N/A";

    const date = new Date(value);

    if (Number.isNaN(date.getTime())) {
      return String(value);
    }

    return date.toLocaleString();
  };

  const getEmployee = (alert) => {
    return (
      alert.employee_id ||
      alert.employeeId ||
      alert.user_id ||
      "Unknown"
    );
  };

  return (
    <AuthGuard>
      <main className="min-h-screen bg-slate-950 text-white">
        {/* Header */}
        <header className="border-b border-slate-800 bg-slate-900/80">
          <div className="mx-auto flex max-w-7xl items-center justify-between px-6 py-5">
            <div>
              <h1 className="text-2xl font-bold">
                Security Alerts
              </h1>

              <p className="mt-1 text-sm text-slate-400">
                Monitor and review security alerts generated by ITBIS.
              </p>
            </div>

            <div className="flex gap-3">
              <Link
                href="/dashboard"
                className="rounded-lg border border-slate-700 px-4 py-2 text-sm text-slate-300 transition hover:bg-slate-800"
              >
                Dashboard
              </Link>

              <button
                onClick={loadAlerts}
                disabled={loading}
                className="rounded-lg bg-blue-600 px-4 py-2 text-sm font-medium transition hover:bg-blue-500 disabled:opacity-50"
              >
                {loading ? "Refreshing..." : "Refresh"}
              </button>
            </div>
          </div>
        </header>

        <div className="mx-auto max-w-7xl px-6 py-8">
          {/* Error */}
          {error && (
            <div className="mb-6 rounded-xl border border-red-500/30 bg-red-500/10 p-4">
              <p className="font-medium text-red-400">
                Alert data unavailable
              </p>

              <p className="mt-1 text-sm text-red-300/80">
                {error}
              </p>
            </div>
          )}

          {/* Statistics */}
          <section className="grid grid-cols-1 gap-4 sm:grid-cols-2 lg:grid-cols-5">
            <StatCard
              title="Total Alerts"
              value={stats.total}
              description="All security alerts"
            />

            <StatCard
              title="Critical"
              value={stats.critical}
              description="Critical alerts"
              valueClass="text-red-400"
            />

            <StatCard
              title="High"
              value={stats.high}
              description="High severity"
              valueClass="text-orange-400"
            />

            <StatCard
              title="Medium"
              value={stats.medium}
              description="Medium severity"
              valueClass="text-yellow-400"
            />

            <StatCard
              title="Low"
              value={stats.low}
              description="Low severity"
              valueClass="text-green-400"
            />
          </section>

          {/* Filters */}
          <section className="mt-8 rounded-2xl border border-slate-800 bg-slate-900 p-5">
            <div className="flex flex-col gap-4 lg:flex-row lg:items-center lg:justify-between">
              <div>
                <h2 className="font-semibold">
                  Alert Management
                </h2>

                <p className="mt-1 text-sm text-slate-500">
                  Search and filter security alerts.
                </p>
              </div>

              <div className="flex flex-col gap-3 sm:flex-row">
                <input
                  type="text"
                  placeholder="Search employee, message..."
                  value={search}
                  onChange={(e) =>
                    setSearch(e.target.value)
                  }
                  className="w-full rounded-lg border border-slate-700 bg-slate-950 px-4 py-2 text-sm text-white outline-none placeholder:text-slate-500 focus:border-blue-500 sm:w-64"
                />

                <select
                  value={severityFilter}
                  onChange={(e) =>
                    setSeverityFilter(e.target.value)
                  }
                  className="rounded-lg border border-slate-700 bg-slate-950 px-4 py-2 text-sm text-white outline-none focus:border-blue-500"
                >
                  <option value="all">
                    All Severity
                  </option>

                  <option value="critical">
                    Critical
                  </option>

                  <option value="high">
                    High
                  </option>

                  <option value="medium">
                    Medium
                  </option>

                  <option value="low">
                    Low
                  </option>
                </select>
              </div>
            </div>
          </section>

          {/* Alerts Table */}
          <section className="mt-5 overflow-hidden rounded-2xl border border-slate-800 bg-slate-900">
            {loading ? (
              <div className="flex min-h-[350px] items-center justify-center">
                <div className="text-center">
                  <div className="mx-auto h-10 w-10 animate-spin rounded-full border-4 border-slate-700 border-t-blue-500" />

                  <p className="mt-4 text-sm text-slate-500">
                    Loading security alerts...
                  </p>
                </div>
              </div>
            ) : filteredAlerts.length === 0 ? (
              <div className="px-6 py-16 text-center">
                <div className="text-4xl">✓</div>

                <h3 className="mt-4 text-lg font-semibold">
                  No alerts found
                </h3>

                <p className="mt-2 text-sm text-slate-500">
                  No security alerts match your current filters.
                </p>
              </div>
            ) : (
              <div className="overflow-x-auto">
                <table className="w-full min-w-[950px]">
                  <thead className="border-b border-slate-800 bg-slate-950/60">
                    <tr className="text-left text-xs uppercase tracking-wider text-slate-500">
                      <th className="px-6 py-4">
                        Alert
                      </th>

                      <th className="px-6 py-4">
                        Employee
                      </th>

                      <th className="px-6 py-4">
                        Severity
                      </th>

                      <th className="px-6 py-4">
                        Status
                      </th>

                      <th className="px-6 py-4">
                        Assigned To
                      </th>

                      <th className="px-6 py-4">
                        Created
                      </th>

                      <th className="px-6 py-4 text-right">
                        Action
                      </th>
                    </tr>
                  </thead>

                  <tbody className="divide-y divide-slate-800">
                    {filteredAlerts.map((alert, index) => (
                      <tr
                        key={
                          alert.id ||
                          alert._id ||
                          `alert-${index}`
                        }
                        className="transition hover:bg-slate-800/40"
                      >
                        {/* Message */}
                        <td className="max-w-[320px] px-6 py-5">
                          <div className="font-medium text-slate-200">
                            {alert.message ||
                              "Security alert"}
                          </div>

                          {alert.incident_id && (
                            <div className="mt-1 text-xs text-slate-500">
                              Incident #{alert.incident_id}
                            </div>
                          )}
                        </td>

                        {/* Employee */}
                        <td className="px-6 py-5">
                          <span className="rounded-lg bg-slate-800 px-3 py-2 text-xs font-medium text-slate-300">
                            {getEmployee(alert)}
                          </span>
                        </td>

                        {/* Severity */}
                        <td className="px-6 py-5">
                          <span
                            className={`rounded-full border px-3 py-1 text-xs font-semibold capitalize ${getSeverityClass(
                              alert.severity
                            )}`}
                          >
                            {alert.severity ||
                              "Unknown"}
                          </span>
                        </td>

                        {/* Status */}
                        <td className="px-6 py-5">
                          <span
                            className={`rounded-full border px-3 py-1 text-xs font-medium capitalize ${getStatusClass(
                              alert.status
                            )}`}
                          >
                            {alert.status || "open"}
                          </span>
                        </td>

                        {/* Assigned */}
                        <td className="px-6 py-5 text-sm text-slate-400">
                          {alert.assigned_to ||
                            alert.assignedTo ||
                            "Unassigned"}
                        </td>

                        {/* Date */}
                        <td className="px-6 py-5 text-sm text-slate-400">
                          {formatDate(
                            alert.created_at ||
                              alert.createdAt
                          )}
                        </td>

                        {/* Action */}
                        <td className="px-6 py-5 text-right">
                          <Link
                            href="/investigation"
                            className="rounded-lg border border-slate-700 px-3 py-2 text-xs font-medium text-slate-300 transition hover:border-blue-500 hover:text-blue-400"
                          >
                            Investigate
                          </Link>
                        </td>
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>
            )}
          </section>

          {/* Navigation */}
          <section className="mt-8 grid grid-cols-1 gap-4 md:grid-cols-3">
            <NavigationCard
              href="/anomalies"
              title="Anomaly Detection"
              description="Review rule-based and machine-learning anomalies."
            />

            <NavigationCard
              href="/investigation"
              title="Threat Investigation"
              description="Investigate suspicious employees and security incidents."
            />

            <NavigationCard
              href="/employees"
              title="Employee Intelligence"
              description="View employee risk scores and UEBA intelligence."
            />
          </section>
        </div>
      </main>
    </AuthGuard>
  );
}

function StatCard({
  title,
  value,
  description,
  valueClass = "text-white",
}) {
  return (
    <div className="rounded-2xl border border-slate-800 bg-slate-900 p-5">
      <p className="text-xs font-medium uppercase tracking-wider text-slate-500">
        {title}
      </p>

      <p
        className={`mt-2 text-3xl font-bold ${valueClass}`}
      >
        {value}
      </p>

      <p className="mt-1 text-xs text-slate-500">
        {description}
      </p>
    </div>
  );
}

function NavigationCard({
  href,
  title,
  description,
}) {
  return (
    <Link
      href={href}
      className="group rounded-2xl border border-slate-800 bg-slate-900 p-5 transition hover:border-blue-500/50 hover:bg-slate-800/60"
    >
      <h3 className="font-semibold text-white group-hover:text-blue-400">
        {title}
      </h3>

      <p className="mt-2 text-sm leading-6 text-slate-400">
        {description}
      </p>

      <div className="mt-4 text-sm text-blue-400">
        Open →
      </div>
    </Link>
  );
}